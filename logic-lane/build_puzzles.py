#!/usr/bin/env python3
"""Turn Lorelai's puzzles.json into logic-lane/puzzles.js.
Only logic_grids are shipped. ideas_for_later and art briefs stay out.
"""
import json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_SRC = Path("/workspace/homeschool/arcade-puzzles/puzzles.json")

def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SRC
    if not src.is_file():
        sys.exit("missing source puzzles.json: " + str(src))
    data = json.load(open(src, encoding="utf-8"))
    grids = data["logic_grids"] if isinstance(data, dict) else data
    out_grids = []
    for g in grids:
        item = {k: g[k] for k in g if k != "art_hint"}
        out_grids.append(item)
    payload = {
        "schema_version": data.get("schema_version", 1) if isinstance(data, dict) else 1,
        "source": data.get("source", "") if isinstance(data, dict) else "",
        "logic_grids": out_grids,
    }
    js = (
        "/* Logic Lane puzzle data. Generated by build_puzzles.py from Lorelai's grids.\n"
        "   ideas_for_later and art_hint are not included. Answers stay in this file so\n"
        "   the game can check the grid and the final question.\n"
        "*/\n"
        "(function (root) {\n"
        "  \"use strict\";\n"
        "  root.LOGIC_LANE_DATA = "
        + json.dumps(payload, ensure_ascii=False, indent=2)
        + ";\n"
        "  root.LOGIC_LANE_PUZZLES = root.LOGIC_LANE_DATA.logic_grids;\n"
        "})(typeof window !== \"undefined\" ? window : globalThis);\n"
    )
    dest = HERE / "puzzles.js"
    dest.write_text(js, encoding="utf-8")
    print("wrote", dest, "grids=", len(out_grids), "bytes=", dest.stat().st_size)

if __name__ == "__main__":
    main()
